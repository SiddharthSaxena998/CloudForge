/**
 * Own-Dockerfile support.
 *
 * CloudForge writes a Dockerfile for known frameworks and marks it with GENERATED_MARKER. A
 * Dockerfile WITHOUT that marker belongs to the user (from their repo/archive or saved in the
 * in-browser editor) and is used as it is.
 */
const fs = require('fs');
const path = require('path');

const GENERATED_MARKER = '# Generated by CloudForge';

const isGenerated = (content) => {
  const first = String(content).split('\n').find((l) => l.trim() !== '');
  return Boolean(first && first.trim().startsWith(GENERATED_MARKER));
};

/** Removes the marker line (used when the user edits the Dockerfile: from then on it is theirs). */
const stripMarker = (content) => {
  const lines = String(content).split('\n');
  const i = lines.findIndex((l) => l.trim() !== '');
  if (i >= 0 && lines[i].trim().startsWith(GENERATED_MARKER)) lines.splice(i, 1);
  return lines.join('\n');
};

/** { path, content } of the user's own Dockerfile in the project root, or null. Symlinks are ignored. */
const findUserDockerfile = (sourcePath) => {
  try {
    if (!sourcePath) return null;
    const file = path.join(sourcePath, 'Dockerfile');
    const stat = fs.lstatSync(file);
    if (!stat.isFile() || stat.size > 256 * 1024) return null;
    const content = fs.readFileSync(file, 'utf8');
    return isGenerated(content) ? null : { path: file, content };
  } catch (_) {
    return null;
  }
};

const validPort = (value) => Number.isInteger(value) && value >= 1 && value <= 65535;

/** First `EXPOSE <port>[/tcp]` of a Dockerfile (variables like $PORT and udp ports are skipped). */
const parseExposedPort = (content) => {
  for (const line of String(content).split('\n')) {
    const m = /^\s*EXPOSE\s+(.+)$/i.exec(line);
    if (!m) continue;
    for (const token of m[1].trim().split(/\s+/)) {
      const t = /^(\d{1,5})(?:\/(tcp|udp))?$/i.exec(token);
      if (t && t[2]?.toLowerCase() !== 'udp' && validPort(Number(t[1]))) return Number(t[1]);
    }
  }
  return null;
};

module.exports = { GENERATED_MARKER, isGenerated, stripMarker, findUserDockerfile, validPort, parseExposedPort };
